#include <stdio.h>

/* Практическая работа №4, задание 4.4, вариант 7.
   Сумма обратных: S = 1/1 + 1/2 + ... + 1/N. */

int main(void)
{
    int n;
    int i = 1;
    double s = 0.0;   /* аккумулятор суммы, нейтральный элемент - 0 */

    printf("Введите N: ");
    if (scanf("%d", &n) != 1 || n <= 0)
    {
        printf("N должно быть положительным целым числом\n");
        return 0;
    }

    /* Для накопления суммы используется +=, потому что каждое новое
       слагаемое добавляется к уже накопленному значению (s = s + x),
       а начальное значение аккумулятора равно 0. Для произведения
       применяется *=, так как каждый множитель умножается на накопленное
       значение, а начальное значение равно 1 (нейтральный элемент
       умножения; при 0 всё произведение осталось бы нулевым).
       Здесь используется 1.0 / i, а не 1 / i: целочисленное деление
       дало бы 0 для всех i > 1. */
    while (i <= n)
    {
        s += 1.0 / i;
        i++;
    }

    printf("S = %.6f\n", s);

    return 0;
}
