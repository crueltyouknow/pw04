#include <stdio.h>

/* Практическая работа №4, задание 4.3, вариант 1.
   Арифметическая прогрессия: a[i] = a[i-1] + 2, a[1] = 1. */

int main(void)
{
    int n;
    int a = 1;       /* текущий элемент последовательности */
    int i = 0;       /* счетчик выведенных элементов */

    printf("Введите N: ");
    if (scanf("%d", &n) != 1 || n <= 0)
    {
        printf("N должно быть положительным целым числом\n");
        return 0;
    }

    /* Постфиксный инкремент i++ возвращает старое значение и затем
       увеличивает переменную; префиксный ++i сначала увеличивает,
       а затем возвращает новое значение. Здесь порядок важен: счетчик
       должен изменяться после проверки условия и вывода элемента,
       иначе мы выведем на один элемент больше или меньше, чем N. */
    while (i++ < n)
    {
        printf("%d ", a);
        a += 2;
    }
    printf("\n");

    return 0;
}
