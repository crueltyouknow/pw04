#include <stdio.h>

/* Практическая работа №4, задание 4.5, вариант 11.
   Функция k_to_c: C = K - 273.15. */

/* Функция принимает double, а не float: double имеет около 15-16 значащих
   цифр против 6-7 у float, поэтому коэффициент 273.15 и результат
   вычитания не искажаются погрешностью округления. Кроме того, double -
   основной вещественный тип в Си: литерал 273.15 и спецификатор %lf
   в scanf работают именно с ним. */
double k_to_c(double k)
{
    const double offset = 273.15;
    return k - offset;
}

int main(void)
{
    double value;

    printf("Введите температуру в Кельвинах (не число или EOF для выхода):\n");

    /* scanf возвращает количество успешно считанных значений.
       При вводе буквы он вернет 0 и не извлечет символ из буфера, так что
       без проверки == 1 цикл бесконечно пытался бы прочитать тот же
       символ. При EOF scanf возвращает EOF (-1), что тоже не равно 1,
       и цикл корректно завершается. */
    while (scanf("%lf", &value) == 1)
    {
        printf("%.2f K = %.2f C\n", value, k_to_c(value));
    }

    return 0;
}
